# Regenerate dts/t8020-pmgr.dtsi from the ADT inside the iPhone11,6 IPSW.
#
# The heavy lifting is m1n1's pmgr_adt2dt.py, which reads the real register
# offsets out of the ADT. This wrapper only reshapes its output to the
# convention the Apple device trees already use:
#
#   - the two power-management nodes are declared in t8020.dtsi, so drop the
#     copies the generator prints and keep just the overlays
#   - pmgr0 and pmgr1 become pmgr and pmgr_mini to match T8015
#   - the pwrstate fallback becomes apple,pmgr-pwrstate, which is what the
#     driver actually binds against
#
# Needs pyimg4, and a checkout of m1n1 with the construct module importable.

set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
im4p=${1:-}
if [ -z "$im4p" ]; then
	echo "usage: $0 <DeviceTree.d331pap.im4p>" >&2
	echo "it is in Firmware/all_flash of an unpacked iPhone11,6 IPSW" >&2
	exit 1
fi
m1n1=${M1N1_SRC:-$root/build/m1n1}
python=${PYTHON:-$root/build/venv/bin/python}
adt=$root/build/adt-d331p.bin
out=$root/dts/t8020-pmgr.dtsi

pyimg4 im4p extract -i "$im4p" -o "$adt"

{
	cat <<'EOF'
// SPDX-License-Identifier: GPL-2.0+ OR MIT
/*
 * PMGR power domains for the Apple T8020 "A12" SoC
 *
 * Generated by tools/gen-pmgr.sh from the ADT in the iPhone11,6 IPSW.
 * Do not edit by hand, regenerate instead.
 *
 * Copyright (c) 2026, kiki <kieran@lavato.net>
 */

EOF
	cd "$m1n1/proxyclient"
	"$python" tools/pmgr_adt2dt.py "$adt" 2>/dev/null | sed \
		-e '/^pmgr[01]: power-management@/,/^};$/d' \
		-e 's/^&pmgr0 {/\&pmgr {/' \
		-e 's/^&pmgr1 {/\&pmgr_mini {/' \
		-e 's/"apple,t8103-pmgr-pwrstate"/"apple,pmgr-pwrstate"/' |
		# A few ADT labels contain hyphens, which are not legal in a DTS
		# label. T8015 spells those with underscores, so do the same. The
		# label = "..." strings are left alone, they do not start with ps_.
		sed -e ':a' -e 's/\(ps_[A-Za-z0-9_]*\)-/\1_/' -e 'ta'
} > "$out"

echo "wrote $out ($(grep -c 'power-controller@' "$out") power domains)"
